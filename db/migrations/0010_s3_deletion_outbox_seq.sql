-- 与重复入队) 都从一个全局序列取一个新值作 seq, 消费者只按 (s3_key, seq) 删行。不用「从 0 起、
-- 冲突时 + 1」: 续锁失败时两个 drain 会并发, 一个删掉 (K, 0) 之后重新插入的行又是 (K, 0),
-- 另一个按旧读数就把它删了 (复核复现的 ABA)。
